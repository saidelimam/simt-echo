import java.util.Properties

plugins {
    alias(libs.plugins.androidApplication)
    alias(libs.plugins.composeCompiler)
    // W10-04: registers the `baselineProfile` dependency configuration so
    // the generated profile ships in release builds (docs/perf.md).
    alias(libs.plugins.baselineprofile)
}

android {
    namespace = "app.simt.echo"
    compileSdk = libs.versions.android.compileSdk.get().toInt()

    // Plan §0.6: app secrets live in the gitignored local.properties and
    // reach the app only as BuildConfig constants — never committed.
    val localProperties = Properties().apply {
        val file = rootProject.file("local.properties")
        if (file.exists()) file.inputStream().use(::load)
    }

    defaultConfig {
        // Plan §0.6: BuildConfig constants from gitignored local.properties.
        buildConfigField("String", "ECHO_APP_TOKEN", "\"" + (localProperties.getProperty("ECHO_APP_TOKEN", "") ?: "") + "\"")
        buildConfigField("String", "WORKERS_API_BASE", "\"" + (localProperties.getProperty("WORKERS_API_BASE", "") ?: "") + "\"")
        applicationId = "app.simt.echo"
        minSdk = libs.versions.android.minSdk.get().toInt()
        targetSdk = libs.versions.android.targetSdk.get().toInt()
        // W9-10 version discipline: versionName is MAJOR.MINOR.PATCH;
        // versionCode = MAJOR * 10000 + MINOR * 100 + PATCH, strictly
        // increasing per release. Bump the components below; versionCode
        // follows automatically. Documented in docs/release.md.
        val appVersionMajor = 0
        val appVersionMinor = 2
        val appVersionPatch = 0
        versionCode = appVersionMajor * 10000 + appVersionMinor * 100 + appVersionPatch
        versionName = "$appVersionMajor.$appVersionMinor.$appVersionPatch"
    }

    signingConfigs {
        create("release") {
            // W9-10: release keystore lives OUTSIDE git (e.g.
            // ~/.keystores/echo-release.jks — see docs/release.md).
            // Env-var wiring only; nothing secret is read from the repo.
            val storePath = System.getenv("ECHO_RELEASE_STORE_FILE")
            if (!storePath.isNullOrBlank() && file(storePath).exists()) {
                storeFile = file(storePath)
                storePassword = System.getenv("ECHO_RELEASE_STORE_PASSWORD")
                keyAlias = System.getenv("ECHO_RELEASE_KEY_ALIAS")
                keyPassword = System.getenv("ECHO_RELEASE_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        release {
            // W9-01: release builds talk to production without developer
            // local.properties. WORKERS_API_BASE defaults to the deployed
            // worker (env ECHO_PROD_API_BASE overrides); ECHO_APP_TOKEN
            // comes ONLY from env ECHO_PROD_APP_TOKEN (never committed).
            // Debug keeps the local.properties behaviour above.
            buildConfigField(
                "String", "WORKERS_API_BASE",
                "\"" + (System.getenv("ECHO_PROD_API_BASE")
                    ?: "https://api.echo.simt.app") + "\"",
            )
            buildConfigField(
                "String", "ECHO_APP_TOKEN",
                "\"" + (System.getenv("ECHO_PROD_APP_TOKEN") ?: "") + "\"",
            )            // W9-10 minify decision: stays OFF — see docs/release.md.
            // Keep rules are committed (proguard-rules.pro) for the future
            // enablement; the release smoke run below proves the shipped
            // configuration, not an untested minified one.
            isMinifyEnabled = false
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro",
            )
            // Signed release when the env-wired keystore exists; otherwise
            // gradle debug signing so assembleRelease still smoke-runs
            // locally without secrets. CI never signs releases.
            val storePath = System.getenv("ECHO_RELEASE_STORE_FILE")
            signingConfig = if (!storePath.isNullOrBlank() && file(storePath).exists()) {
                signingConfigs.getByName("release")
            } else {
                signingConfigs.getByName("debug")
            }
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_11
        targetCompatibility = JavaVersion.VERSION_11
    }

    buildFeatures {
        buildConfig = true
    }
}

dependencies {
    implementation(project(":shared"))
    implementation(libs.androidx.activity.compose)
    // W10-04: ProfileInstaller lets release builds consume the Baseline
    // Profile generated by :benchmark on first install.
    implementation(libs.profileinstaller)
    // W10-04: the Baseline Profile artefact collected from :benchmark's
    // generator (connectedNonMinifiedReleaseAndroidTest +
    // collectNonMinifiedReleaseBaselineProfile — see docs/perf.md);
    // release builds install it, debug builds ignore it.
    baselineProfile(project(":benchmark"))
    // W10-04: JankStats summaries in debug only — DebugJankStats lives in
    // the debug source set and MainActivity installs it via reflection, so
    // release never loads this dependency.
    debugImplementation(libs.metrics.performance)
    // W9-11: plain-JVM assertions over the launcher icon + splash XML.
    testImplementation(libs.junit.junit)
}
